"""Named-TCC inspection and verification rejection tests in fresh contexts."""
import asyncio
from pathlib import Path
import sys

import pytest

AGENT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(AGENT))
from server import PVSClient, RPCError


@pytest.fixture
def inspection_context(tmp_path):
    (tmp_path / "inspection_fixture.pvs").write_text(
        "inspection_fixture: THEORY\nBEGIN\n"
        "  reciprocal(n: int): real = 1 / n\n"
        "  harmless: LEMMA TRUE\n"
        "  declared_fact: AXIOM TRUE\n"
        "END inspection_fixture\n"
    )
    return tmp_path


def formula(context, name):
    return f"{context / 'inspection_fixture.pvs'}#inspection_fixture#{name}"


async def start_client(context):
    client = PVSClient(library_path="")
    try:
        await client.start(str(context), "inspection_fixture", timeout=30)
        return client
    except BaseException:
        await client.close()
        raise


def test_named_tcc_explains_origin_without_changing_proof(inspection_context):
    async def scenario():
        client = await start_client(inspection_context)
        try:
            state = await client.proof_open(formula(inspection_context, "reciprocal_TCC1"))
            sid = state["session_id"]
            before = await client.inspect(sid, "full")
            explanation = await client.inspect(sid, "tcc")
            after = await client.inspect(sid, "full")
            assert before == after
            assert explanation["kind"] == "tcc"
            text = explanation["text"]
            assert "inspection_fixture.reciprocal_TCC1" in text
            assert "subtype" in text.lower()
            assert "Generated by:" in text and "Expected type:" in text
            assert "Obligation:" in text and "n" in text and "0" in text
            assert "not a TCC" not in text and "No current proof" not in text
            # The declaration-origin view remains available after a normal
            # proof step; it must not require a TCC-PROOFSTATE side goal.
            await client.command(sid, "(skosimp*)")
            assert "reciprocal_TCC1" in (await client.inspect(sid, "tcc"))["text"]
            await client.close_session(sid)
        finally:
            await client.close()
    asyncio.run(asyncio.wait_for(scenario(), 45))


def test_verification_rejects_an_axiom_instead_of_empty_success(inspection_context):
    async def scenario():
        client = await start_client(inspection_context)
        try:
            with pytest.raises(RPCError, match="provable"):
                await client.verify(formula(inspection_context, "declared_fact"))
        finally:
            await client.close()
    asyncio.run(asyncio.wait_for(scenario(), 45))


def test_verification_rejects_source_changed_after_preparation(inspection_context):
    async def scenario():
        client = await start_client(inspection_context)
        try:
            target = formula(inspection_context, "harmless")
            opened = await client.proof_open(target)
            sid = opened["session_id"]
            # TRUE may close on entry; check the native record before stepping.
            records = {row["id"]: row for row in await client.proofs(target)}
            if str(records[sid]["status"]).lower() != "proved":
                await client.command(sid, "(grind)")
            await client.save(target, sid)
            path = inspection_context / "inspection_fixture.pvs"
            path.write_text(path.read_text() + "\n% changed after preparation\n")
            with pytest.raises(RPCError, match="changed"):
                await client.verify(target)
        finally:
            await client.close()
    asyncio.run(asyncio.wait_for(scenario(), 45))
